"""
DatasetSession — session-scoped analytical context for one (dataset, conversation) pair.

One dataset can have many sessions.
One conversation always belongs to exactly one session.
Workspace state is stored per session, not per dataset — preventing cross-tab contamination.

Relationship:
  Dataset (1) → Session (N) → Conversation (1:1)
                            → WorkspaceState snapshot (1)
"""
import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any, Dict


@dataclass
class DatasetSession:
    """
    An isolated analytical context for one (dataset, conversation) pair.

    session_id:               UUID — generated by frontend (conversation ID doubles as session ID).
    dataset_id:               UUID of the associated dataset.
    conversation_id:          Frontend conversation ID (same as session_id).
    workspace_state_snapshot: Last known workspace state for session resumption.
    analysis_version:         Engine version that produced this session's results.
    metadata:                 Extensible dict for future session properties.
    """
    session_id: str = field(default_factory=lambda: str(uuid.uuid4()))
    dataset_id: str = ""
    conversation_id: str = ""
    created_at: str = field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )
    last_active_at: str = field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )
    workspace_state_snapshot: Dict[str, Any] = field(default_factory=dict)
    analysis_version: str = "1.0"
    metadata: Dict[str, Any] = field(default_factory=dict)

    def touch(self) -> None:
        """Update last_active_at to now."""
        self.last_active_at = datetime.now(timezone.utc).isoformat()

    def to_dict(self) -> Dict[str, Any]:
        return {
            "session_id": self.session_id,
            "dataset_id": self.dataset_id,
            "conversation_id": self.conversation_id,
            "created_at": self.created_at,
            "last_active_at": self.last_active_at,
            "analysis_version": self.analysis_version,
        }
